/**
 * Stage background art pipeline.
 *
 *   npm run stage-art             → art/raw/stages/<id>.jpg → public/stages/<id>.jpg + src/data/stageArt.ts
 *   npm run stage-art -- --force  → re-process everything (default skips ids that already exist)
 *
 * Unlike hero/monster art these are full scene backgrounds, so no white-background knockout is
 * applied – just a resize + jpeg re-encode (same treatment as scripts/brand.mjs). Stages without a
 * raw file fall back to the default bg-battle.jpg background at runtime (see src/data/stageArt.ts).
 */
import sharp from 'sharp';
import { mkdirSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { basename, extname, join } from 'node:path';

const RAW_DIR = 'art/raw/stages';
const OUT_DIR = 'public/stages';
const REGISTRY = 'src/data/stageArt.ts';

function writeRegistry() {
  const ids = existsSync(OUT_DIR)
    ? readdirSync(OUT_DIR)
        .filter((f) => f.endsWith('.jpg'))
        .map((f) => basename(f, '.jpg'))
        .sort()
    : [];
  const lines = ids.map((id) => `  ${id}: '/stages/${id}.jpg',`).join('\n');
  writeFileSync(
    REGISTRY,
    `/**
 * GENERATED by scripts/stage-art.mjs – do not edit by hand.
 * Drop a raw image into ${RAW_DIR}/<stageId>.jpg and run \`npm run stage-art\`.
 * Stages without art fall back to the default bg-battle.jpg background.
 */
export const STAGE_ART: Record<string, string> = {
${lines}
};

export function stageArt(id: string | undefined): string | undefined {
  return id ? STAGE_ART[id] : undefined;
}
`,
  );
  console.log(`registry (${ids.length}):`, ids.join(', ') || '–');
}

const force = process.argv.includes('--force');

if (!existsSync(RAW_DIR)) {
  console.log(`(no ${RAW_DIR} directory – nothing to process)`);
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  const files = readdirSync(RAW_DIR).filter(
    (f) => statSync(join(RAW_DIR, f)).isFile() && /\.(png|jpe?g|webp)$/i.test(f),
  );
  for (const f of files) {
    const id = basename(f, extname(f)).toLowerCase();
    const out = join(OUT_DIR, `${id}.jpg`);
    if (!force && existsSync(out)) {
      console.log('skip  ', id, `(already in ${OUT_DIR}, use --force to redo)`);
      continue;
    }
    await sharp(join(RAW_DIR, f))
      .resize({ width: 1600, withoutEnlargement: true })
      .jpeg({ quality: 82, mozjpeg: true })
      .toFile(out);
    console.log('wrote ', out);
  }
}
writeRegistry();
