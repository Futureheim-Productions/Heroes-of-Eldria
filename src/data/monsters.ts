/** Base stat profiles by tier – tuned per monster with multipliers */
const TIER_BASE: Record<MonsterTier, Stats> = {
  common: { hp: 900, atk: 85, def: 60, spd: 90, crit: 5, critDmg: 150 },
  mid: { hp: 1500, atk: 125, def: 85, spd: 95, crit: 8, critDmg: 150 },
  elite: { hp: 3200, atk: 175, def: 115, spd: 100, crit: 10, critDmg: 160 },
  unique: { hp: 4200, atk: 200, def: 130, spd: 105, crit: 12, critDmg: 165 },
};

function stats(tier: MonsterTier, m: Partial<Stats> = {}): Stats {
  const b = TIER_BASE[tier];
  return {
    hp: Math.round(b.hp * (m.hp ?? 1)),
    atk: Math.round(b.atk * (m.atk ?? 1)),
    def: Math.round(b.def * (m.def ?? 1)),
    spd: Math.round(b.spd * (m.spd ?? 1)),
    crit: b.crit + (m.crit ?? 0),
    critDmg: b.critDmg + (m.critDmg ?? 0),
  };
}

